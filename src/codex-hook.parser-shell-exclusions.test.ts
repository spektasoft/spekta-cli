import { describe, expect, it } from "vitest";
import { rewritten } from "./codex-hook.test-helpers.js";

describe("Codex inspection hook shell syntax exclusions", () => {
  it.each([
    "ls;whoami",
    "ls | cat",
    "ls >file",
    "ls #comment",
    "ls $(id)",
    "ls `id`",
    "ls $HOME",
    "ls *.ts",
    "ls a?",
    "ls [ab]",
    "ls {a,b}",
    "ls && true",
    "A=1 ls",
    "command ls",
    "bash -c ls",
    "spekta ls",
    "spekta read README.md",
    "spekta find .",
    "rtk ls",
    "rtk find .",
    "find src -exec cat {} \\;",
    "find src -maxdepth 2",
    "find --allowance 100 src",
    "find src --allowance 100",
    "find src -name x; echo unsafe",
    'find src -name "$HOME"',
    "git status --ignored",
    "git log --oneline -n 1",
    "git commit -m message",
    "git diff -- src | cat",
    "git status && git diff",
    "npm test",
    "npm run build",
    "ls 'unterminated",
    'ls "x$HOME"',
    'ls "x`id`"',
    'ls "x\\"',
    "ls\\\nfoo",
    "ls\nfoo",
    "ls\rfoo",
    "ls\u0001foo",
  ])("does not rewrite excluded syntax: %s", (input) =>
    expect(rewritten(input)).toBeUndefined(),
  );
});
